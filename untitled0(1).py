search_box = widgets.Combobox(options=sorted(list(sites_fr.keys())), value="Le Lioran (15)", description='Site:', ensure_option=True, layout={'width': '400px'})

today = datetime.date.today()
tomorrow = today + datetime.timedelta(days=1)
dayaftertomorrow = today + datetime.timedelta(days=2)

day_options = [
    (f"{today.strftime('%A %d %b')} (Aujourd'hui)", 0),
    (f"{tomorrow.strftime('%A %d %b')} (Demain)", 1),
    (f"{dayaftertomorrow.strftime('%A %d %b')} (Après-demain)", 2)
]

day_selector = widgets.Dropdown(options=day_options, value=0, description='Jour:')
out = widgets.Output()

def update_display(site, day_offset):
    if site not in sites_fr: return
    lat, lon, elev = sites_fr[site]
    url = f"https://api.open-meteo.com/v1/forecast?latitude={lat}&longitude={lon}&hourly=wind_speed_10m,wind_direction_10m,wind_speed_1000hPa,wind_speed_950hPa,wind_speed_900hPa,wind_speed_850hPa,wind_speed_800hPa,wind_speed_700hPa,wind_speed_600hPa,wind_direction_1000hPa,wind_direction_950hPa,wind_direction_900hPa,wind_direction_850hPa,wind_direction_800hPa,wind_direction_700hPa,wind_direction_600hPa,boundary_layer_height&wind_speed_unit=kmh&timezone=auto"
    with out:
        clear_output(wait=True)
        try:
            resp = requests.get(url).json()["hourly"]
            target_d = today + datetime.timedelta(days=day_offset)
            times = pd.to_datetime(resp["time"])
            # Mise à jour du masque pour aller de 8h à 22h
            mask = (times.date == target_d) & (times.hour >= 8) & (times.hour <= 22)
            idx = np.where(mask)[0]

            if len(idx) == 0:
                print(f"Aucune donnée disponible.")
                return

            levels = [1000, 950, 900, 850, 800, 700, 600]
            alts_ref = np.array([10, 110, 540, 990, 1450, 1950, 3010, 4200])
            target_alts = np.arange(0, 4201, 200)

            fig, ax = plt.subplots(figsize=(14, 8))
            ax.fill_between(range(len(idx)), 0, elev, color='#5D4037', alpha=0.9, zorder=10)

            # --- Tracé du plafond (BLH) ---
            blh = np.array(resp["boundary_layer_height"])[idx] + elev
            ax.plot(range(len(idx)), blh, color='red', linestyle='--', linewidth=2, label='Plafond (BLH)', zorder=25)

            for j, step in enumerate(idx):
                s_vals = np.array([resp["wind_speed_10m"][step]] + [resp[f"wind_speed_{l}hPa"][step] for l in levels])
                d_vals = np.array([resp["wind_direction_10m"][step]] + [resp[f"wind_direction_{l}hPa"][step] for l in levels])

                f_speed = interp1d(alts_ref, s_vals, fill_value="extrapolate", bounds_error=False)
                f_dir = interp1d(alts_ref, d_vals, fill_value="extrapolate", bounds_error=False)

                for alt in target_alts:
                    if alt > elev + 50:
                        s = f_speed(alt); d = f_dir(alt)
                        color = "#90A4AE" if s < 12 else ("#FB8C00" if s < 22 else "#B71C1C")
                        ax.quiver(j, alt, np.cos(np.radians(270-d)), np.sin(np.radians(270-d)), color=color, scale=35, pivot='middle', alpha=0.8, zorder=15)
                        ax.text(j, alt + 100, f"{int(s)}", color='black', fontsize=9, weight='bold', ha='center', va='bottom', zorder=100, bbox=dict(facecolor='white', alpha=0.8, edgecolor='none', pad=1))

            ax.set_title(f"Vent et Plafond pour {site} - {target_d.strftime('%A %d %b')}", fontsize=14, weight='bold')
            ax.set_xticks(range(len(idx))); ax.set_xticklabels(times[mask].strftime('%Hh'))
            ax.set_ylim(0, 4500)
            ax.grid(True, linestyle=':', alpha=0.5)
            ax.legend(loc='upper right')
            plt.show()
            plt.close(fig)
        except Exception as e:
            print(f"Erreur: {e}")

widgets.interactive_output(update_display, {'site': search_box, 'day_offset': day_selector})
display(widgets.VBox([search_box, day_selector, out]))

